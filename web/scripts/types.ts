// Writes src/api/types.ts from the JSON Schema of each kind in internal/api/schema, or,
// given --check, fails where what is committed is not what it would write.
//
// The schemas refer to each other by file, common.json holding what they share, so
// they are put together first into one schema whose $defs hold every definition
// under one name: common's as they are named there, a kind's own prefixed with the
// kind, and each kind and the manifest as its title followed by Record. Every declaration is then
// written once, named by its title.

import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { compile, type JSONSchema } from 'json-schema-to-typescript'

const schemaDir = fileURLToPath(new URL('../../internal/api/schema/', import.meta.url))
const target = fileURLToPath(new URL('../src/api/types.ts', import.meta.url))

type Node = { [key: string]: unknown }

const pascal = (word: string) =>
  word
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('')

// rewrite hands back node with every $ref pointing into the bundle, a ref within the
// file it came from being read by local. Two things that say nothing of a type are
// left out, each of which would otherwise make one: the description beside a $ref,
// which would declare a copy of what it refers to, and a oneOf of nothing but
// required lists, which says which of an object's keys must be there.
function rewrite(node: unknown, local: (name: string) => string): unknown {
  if (Array.isArray(node)) return node.map((item) => rewrite(item, local))
  if (node === null || typeof node !== 'object') return node
  const entries = Object.entries(node as Node).filter(([key, value]) => {
    if ('$ref' in (node as Node) && (key === 'description' || key === 'title')) return false
    const onlyRequired = (member: unknown) =>
      typeof member === 'object' && member !== null && Object.keys(member).every((k) => k === 'required')
    return !(key === 'oneOf' && Array.isArray(value) && value.every(onlyRequired))
  })
  const out: Node = {}
  if (entries.length > 0 && entries.every(([key, value]) => key === 'description' && typeof value === 'string')) {
    // a schema saying nothing of its value takes any, where the generator would
    // otherwise make an object of it
    out.tsType = 'unknown'
  }
  for (const [key, value] of entries) {
    if (key === '$ref' && typeof value === 'string') {
      const [file, pointer = ''] = value.split('#')
      const name = pointer.replace(/^\/\$defs\//, '')
      out[key] = '#/$defs/' + (file === '' ? local(name) : file === 'common.json' ? name : fail(value))
    } else {
      out[key] = rewrite(value, local)
    }
  }
  return out
}

function fail(ref: string): never {
  throw new Error(`a schema refers to ${ref}, which is neither in its own file nor in common.json`)
}

export async function bundle(): Promise<JSONSchema> {
  const files = (await readdir(schemaDir)).filter((f) => f.endsWith('.json')).sort()
  const defs: Node = {}
  const properties: Node = {}
  for (const file of files) {
    const name = file.replace(/\.json$/, '')
    const schema = JSON.parse(await readFile(schemaDir + file, 'utf8')) as Node
    const { $defs = {}, ...whole } = schema as Node & { $defs?: Node }
    delete whole.$schema
    delete whole.$id
    const own = (def: string) => (name === 'common' ? def : name + pascal(def))
    for (const [def, value] of Object.entries($defs)) {
      const written = rewrite(value, own) as Node
      defs[own(def)] = '$ref' in written ? written : { ...written, title: pascal(own(def)) }
    }
    if (name !== 'common') {
      const title = (whole.title as string) + 'Record'
      defs[title] = { ...(rewrite(whole, own) as Node), title }
      properties[name] = { $ref: '#/$defs/' + title }
    }
  }
  return {
    title: 'Schemas',
    description: 'Every kind of record and the manifest, by the word origins schema takes.',
    type: 'object',
    properties,
    additionalProperties: false,
    $defs: defs,
  } as JSONSchema
}

export async function generate(): Promise<string> {
  return compile(await bundle(), 'Schemas', {
    bannerComment:
      '// Generated by `npm run types` from internal/api/schema; do not edit by hand.',
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    format: true,
    style: { semi: false, singleQuote: true, printWidth: 100 },
  })
}

const written = await generate()
if (process.argv.includes('--check')) {
  const committed = await readFile(target, 'utf8').catch(() => '')
  if (committed !== written) {
    console.error('src/api/types.ts is not what the schema generates: run npm run types')
    process.exit(1)
  }
} else {
  await writeFile(target, written)
}
