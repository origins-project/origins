// Writes internal/chart/draw/colours.go from the light theme of src/ui/tokens.css, so
// that a chart exported is drawn in the colours of the one on the page, or, given
// --check, fails where what is committed is not what it would write.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const tokens = fileURLToPath(new URL('../src/ui/tokens.css', import.meta.url))
const target = fileURLToPath(new URL('../../internal/chart/draw/colours.go', import.meta.url))

export async function generate(): Promise<string> {
  const css = await readFile(tokens, 'utf8')
  const selector = ":root,\n[data-theme='light'] {"
  const start = css.indexOf(selector)
  if (start < 0) throw new Error('tokens.css has no light theme')
  const body = css.slice(start, css.indexOf('}', start))
  const colours = [...body.matchAll(/--([a-z0-9-]+):\s*#([0-9a-f]{3}|[0-9a-f]{6});/g)].map((m) => ({
    name: m[1]!.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase()),
    hex: m[2]!.length === 3 ? m[2]!.replace(/./g, (c) => c + c) : m[2]!,
  }))
  const width = Math.max(...colours.map((c) => c.name.length))
  return [
    '// Code generated by `npm run colours` from web/src/ui/tokens.css; DO NOT EDIT.',
    '',
    'package draw',
    '',
    'import "github.com/tdewolff/canvas"',
    '',
    "// The colours of the pages' light theme, each named as its token is.",
    'var (',
    ...colours.map((c) => `\t${c.name.padEnd(width)} = canvas.Hex("#${c.hex}")`),
    ')',
    '',
  ].join('\n')
}

const written = await generate()
if (process.argv.includes('--check')) {
  const committed = await readFile(target, 'utf8').catch(() => '')
  if (committed !== written) {
    console.error('internal/chart/draw/colours.go is not what tokens.css generates: run npm run colours')
    process.exit(1)
  }
} else {
  await writeFile(target, written)
}
